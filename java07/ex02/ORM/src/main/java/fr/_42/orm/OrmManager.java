package fr._42.orm;

import fr._42.orm.annotations.OrmColumn;
import fr._42.orm.annotations.OrmColumnId;
import fr._42.orm.annotations.OrmEntity;

import java.lang.reflect.Constructor;
import java.lang.reflect.Field;
import java.sql.*;
import java.util.ArrayList;
import java.util.List;

public class OrmManager implements AutoCloseable {
    private static final String URL = "jdbc:postgresql://localhost:5432/orm_db";
    private static final String USER = "postgres";
    private static final String PASSWORD = "root";

    private final Connection connection;

    public OrmManager(Class<?>... entityClasses) throws SQLException {
        connection = DriverManager.getConnection(URL, USER, PASSWORD);

        try {
            for (Class<?> entityClass : entityClasses) {
                createTable(entityClass);
            }
        } catch (SQLException | RuntimeException e) {
            connection.close();
            throw e;
        }

        System.out.println("OrmManager initialized.");
    }

    // Drop the old table and create a new one.
    private void createTable(Class<?> entityClass) throws SQLException {
        EntityInfo info = getEntityInfo(entityClass);

        String dropSql = "DROP TABLE IF EXISTS " + info.table;
        System.out.println(dropSql);

        try (Statement statement = connection.createStatement()) {
            statement.executeUpdate(dropSql);
        }

        List<String> definitions = new ArrayList<>();

        for (Field field : entityClass.getDeclaredFields()) {
            if (field.isAnnotationPresent(OrmColumnId.class)) {
                definitions.add(field.getName()
                        + " BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
            } else if (field.isAnnotationPresent(OrmColumn.class)) {
                OrmColumn column = field.getAnnotation(OrmColumn.class);

                definitions.add(column.name() + " "
                        + sqlType(field.getType(), column.length()));
            }
        }

        String createSql = "CREATE TABLE " + info.table
                + " (" + String.join(", ", definitions) + ")";

        System.out.println(createSql);

        try (Statement statement = connection.createStatement()) {
            statement.executeUpdate(createSql);
        }
    }

    // INSERT an object and assign its generated ID.
    public void save(Object entity) throws SQLException {
        EntityInfo info = getEntityInfo(entity.getClass());
        List<Field> fields = getColumnFields(entity.getClass());

        List<Field> insertFields = new ArrayList<>();

        for (Field field : fields) {
            if (!field.isAnnotationPresent(OrmColumnId.class)) {
                insertFields.add(field);
            }
        }

        String sql;

        if (insertFields.isEmpty()) {
            sql = "INSERT INTO " + info.table
                    + " DEFAULT VALUES";
        } else {
            List<String> names = new ArrayList<>();

            for (Field field : insertFields) {
                names.add(columnName(field));
            }

            String placeholders = String.join(", ",
                    java.util.Collections.nCopies(insertFields.size(), "?"));

            sql = "INSERT INTO " + info.table
                    + " (" + String.join(", ", names) + ")"
                    + " VALUES (" + placeholders + ")";
        }

        System.out.println(sql);

        try (PreparedStatement statement = connection.prepareStatement(
                sql, Statement.RETURN_GENERATED_KEYS)) {

            for (int i = 0; i < insertFields.size(); i++) {
                Field field = insertFields.get(i);
                field.setAccessible(true);

                try {
                    setParameter(statement, i + 1,
                            field.get(entity), field.getType());
                } catch (IllegalAccessException e) {
                    throw new SQLException("Cannot read field: "
                            + field.getName(), e);
                }
            }

            statement.executeUpdate();

            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (keys.next()) {
                    Field idField = getIdField(entity.getClass());
                    idField.setAccessible(true);

                    try {
                        idField.set(entity, keys.getObject(1, Long.class));
                    } catch (IllegalAccessException e) {
                        throw new SQLException("Cannot assign generated ID", e);
                    }
                }
            }
        }
    }

    // Update all mapped fields, including fields whose value is null.
    public void update(Object entity) throws SQLException {
        EntityInfo info = getEntityInfo(entity.getClass());
        Field idField = getIdField(entity.getClass());
        List<Field> fields = getColumnFields(entity.getClass());

        idField.setAccessible(true);

        Object id;

        try {
            id = idField.get(entity);
        } catch (IllegalAccessException e) {
            throw new SQLException("Cannot read ID", e);
        }

        if (id == null) {
            throw new SQLException("Cannot update an entity without an ID");
        }

        List<Field> updateFields = new ArrayList<>();

        for (Field field : fields) {
            if (!field.isAnnotationPresent(OrmColumnId.class)) {
                updateFields.add(field);
            }
        }

        List<String> assignments = new ArrayList<>();

        for (Field field : updateFields) {
            assignments.add(columnName(field) + " = ?");
        }

        String sql = "UPDATE " + info.table
                + " SET " + String.join(", ", assignments)
                + " WHERE " + idField.getName() + " = ?";

        System.out.println(sql);

        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            for (int i = 0; i < updateFields.size(); i++) {
                Field field = updateFields.get(i);
                field.setAccessible(true);

                try {
                    setParameter(statement, i + 1,
                            field.get(entity), field.getType());
                } catch (IllegalAccessException e) {
                    throw new SQLException("Cannot read field: "
                            + field.getName(), e);
                }
            }

            setParameter(statement, updateFields.size() + 1,
                    id, idField.getType());

            int affectedRows = statement.executeUpdate();

            if (affectedRows == 0) {
                System.out.println("No row found to update.");
            }
        }
    }

    // Find a row by ID and reconstruct the Java object.
    public <T> T findById(Long id, Class<T> aClass) throws SQLException {
        EntityInfo info = getEntityInfo(aClass);
        Field idField = getIdField(aClass);
        List<Field> fields = getColumnFields(aClass);

        String sql = "SELECT * FROM " + info.table
                + " WHERE " + idField.getName() + " = ?";

        System.out.println(sql);

        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            setParameter(statement, 1, id, idField.getType());

            try (ResultSet result = statement.executeQuery()) {
                if (!result.next()) {
                    return null;
                }

                try {
                    Constructor<T> constructor = aClass.getDeclaredConstructor();
                    constructor.setAccessible(true);
                    T entity = constructor.newInstance();

                    for (Field field : fields) {
                        field.setAccessible(true);

                        Object value = result.getObject(columnName(field));

                        if (value != null) {
                            value = convertValue(value, field.getType());
                        }

                        field.set(entity, value);
                    }

                    return entity;
                } catch (ReflectiveOperationException e) {
                    throw new SQLException("Cannot reconstruct entity: "
                            + aClass.getName(), e);
                }
            }
        }
    }

    private EntityInfo getEntityInfo(Class<?> entityClass)
            throws SQLException {
        OrmEntity annotation = entityClass.getAnnotation(OrmEntity.class);

        if (annotation == null) {
            throw new SQLException("Missing @OrmEntity on "
                    + entityClass.getName());
        }

        return new EntityInfo(annotation.table());
    }

    private List<Field> getColumnFields(Class<?> entityClass) {
        List<Field> fields = new ArrayList<>();

        for (Field field : entityClass.getDeclaredFields()) {
            if (field.isAnnotationPresent(OrmColumnId.class)
                    || field.isAnnotationPresent(OrmColumn.class)) {
                fields.add(field);
            }
        }

        return fields;
    }

    private Field getIdField(Class<?> entityClass) throws SQLException {
        Field idField = null;

        for (Field field : entityClass.getDeclaredFields()) {
            if (field.isAnnotationPresent(OrmColumnId.class)) {
                if (idField != null) {
                    throw new SQLException("Multiple @OrmColumnId fields in "
                            + entityClass.getName());
                }
                idField = field;
            }
        }

        if (idField == null) {
            throw new SQLException("Missing @OrmColumnId on "
                    + entityClass.getName());
        }

        return idField;
    }

    private String columnName(Field field) {
        if (field.isAnnotationPresent(OrmColumnId.class)) {
            return field.getName();
        }

        return field.getAnnotation(OrmColumn.class).name();
    }

    private String sqlType(Class<?> type, int length) throws SQLException {
        if (type == String.class) {
            return "VARCHAR(" + length + ")";
        }
        if (type == Integer.class) {
            return "INTEGER";
        }
        if (type == Double.class) {
            return "DOUBLE PRECISION";
        }
        if (type == Boolean.class) {
            return "BOOLEAN";
        }
        if (type == Long.class) {
            return "BIGINT";
        }

        throw new SQLException("Unsupported field type: " + type.getName());
    }

    private int sqlTypeCode(Class<?> type) throws SQLException {
        if (type == String.class)
            return Types.VARCHAR;
        if (type == Integer.class)
            return Types.INTEGER;
        if (type == Double.class)
            return Types.DOUBLE;
        if (type == Boolean.class)
            return Types.BOOLEAN;
        if (type == Long.class)
            return Types.BIGINT;

        throw new SQLException("Unsupported field type: " + type.getName());
    }

    private void setParameter(PreparedStatement statement, int index,
            Object value, Class<?> type) throws SQLException {
        if (value == null) {
            statement.setNull(index, sqlTypeCode(type));
        } else {
            statement.setObject(index, value);
        }
    }

    private Object convertValue(Object value, Class<?> targetType) {
        if (targetType == Long.class) {
            return ((Number) value).longValue();
        }
        if (targetType == Integer.class) {
            return ((Number) value).intValue();
        }
        if (targetType == Double.class) {
            return ((Number) value).doubleValue();
        }

        return value;
    }

    @Override
    public void close() throws SQLException {
        connection.close();
    }

    private static class EntityInfo {
        private final String table;

        private EntityInfo(String table) {
            this.table = table;
        }
    }
}